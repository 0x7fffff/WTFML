/**
 * @file StorageAvailability.hpp
 * @brief 「这块盘还在不在」的一句话判据：给掉盘的用户提示用。
 * @note 掉盘（移动硬盘拔了、网络盘断了）时，产品的每一个文件操作都会各自失败一次：
 * 下载报"某个文件写不进去"、启动报"缺少客户端 JAR"、建目录报"无法创建 Minecraft 目录"。
 * 这些话本身没写错，但用户照着去找，会以为文件被删了、或者以为要改设置里的路径。
 * 这一层只回答一个问题：**这个路径将来会落上去的那块盘，现在还能不能用**。
 *
 * 它不判断"文件在不在"、"有没有权限"、"空间够不够" —— 那些仍然是各自那条路上的事。
 * 也不做重试、不缓存结果：盘可能在任何一刻被拔掉，缓存的"在"就是假绿。
 *
 * NOTE: `isReady()` 说的是卷本身的状态，不等于"每一次 I/O 都会立刻返回"。设备卡在
 * 半死不活的状态时，系统调用可能挂很久 —— 这一层救不了那种情况（见
 * docs/DIRECTORY_SESSION_LOCK.md 里那条"协作式取消"的限制），它能保证的是
 * **系统一旦把错误返回上来，用户看到的是"盘没了"而不是一串看不懂的文件名**。
 */

#pragma once

#include <QString>

namespace StorageAvailability {

/**
 * @brief 问一次：这个路径所在的磁盘现在可用吗？
 * @param path 要写入或读取的路径。**可以还不存在**（`versions/<新实例>`、`saves/<新世界>`
 *             这些落点在写之前本来就没有）—— 那就往上找最近一个已经存在的祖先，
 *             问它落在哪块卷上。找不到任何存在的祖先时，退回路径的根（盘符）。
 * @return 空串 = 可用；非空 = 一句可以直接摆进提示框的人话（含卷根路径）。
 */
QString unavailableReason(const QString &path);

} // namespace StorageAvailability
