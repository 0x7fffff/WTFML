/**
 * @file Animations.hpp
 * @brief 界面动效的**唯一出处**：按下按钮、切换页面、展开/折叠。
 * @author 0x7fffff
 * @date 2026-09-29
 * @note 用户 2026-09-29 原话：「接下来是制作动画，按下按钮，切换页面，展开/折叠的时候的动画，
 *       可以不那么严格的检查，只要不要有元素超出，我人工会校对哪里需要改，可以多个agent
 *       负责不同的页面和部分」。
 *
 * 【这一层只做三件事，一件都不多】
 *
 *   1. **按下按钮**（`installPressAnimation()`）：往整个应用挂一个事件过滤器，谁被按下去就
 *      给谁压暗一档、松开再弹回来。**没有第二处** —— src/ + ui/ 里 97 个 `new QPushButton`
 *      一个字都不用改（这也是为什么走事件过滤器而不是做一个 `WtfmlButton` 子类：那个得改
 *      97 处，而且漏一处就是"有些按钮按下去没反应"）。(2026-10-11 复核)
 *   2. **切换页面**（`pageAppear()` / `overlayAppear()`）：新那一页淡进来，顺带从下面抬
 *      一小段。
 *   3. **展开/折叠**（`animateExpansion()`）：`QTreeView::setAnimated(true)`，交给 Qt 自己
 *      放那一段动画。
 *
 * 【★ 硬要求：不许有元素超出】
 *
 * 这是用户点名的唯一一条验收线（「只要不要有元素超出」），所以这一层给自己上了一条死规矩：
 *
 *   * **除了上拉面板那一个例外，一个像素的几何都不动**。淡入淡出是把控件先渲染到一张
 *     pixmap 上、再按不透明度贴回来（`QGraphicsEffect` 那条路）—— 控件自己的 `geometry()`
 *     从头到尾没变过，布局也没被重新算过。
 *   * 那个例外是底栏那两块上拉面板（`slideUp()`）：它们是**顶层窗口**（`Qt::Popup`），
 *     "从下面滑上来"就是它们的 `pos()` 在动，而它们本来就是一块独立的窗口 —— 动它不会把
 *     任何东西挤出容器，动完也一定停在算好的那个点上（`finished` 里再 `move()` 一次兜底）。
 *   * 自绘的那一份（`AnimEffect::draw()`）**自己钉了一条裁剪**：画之前先按源矩形
 *     `setClipRect(..., IntersectClip)`，就算哪天平移量算错了，也画不到自己那一块之外。
 *   * 页面抬起来那一段（`pageRiseDistance()`）是**把内容整块往下挪着画**，所以是**上面**
 *     多出一条、下面少一条，而不是内容溢出到页面外 —— 源矩形那一剪裁在这里同样管着。
 *
 * 【为什么不走调色板 / 不走样式表】
 *
 * 样式表里已经有 `:pressed` 那一档颜色（`Theme::widgetStyleSheet()`），它是**瞬间**生效的；
 * 样式表的属性动画（`qproperty-…`）要求控件自己有那个 `Q_PROPERTY`，等于还是得改 92 处。
 * 这一层动的是"渲染完的那张图"，所以和样式表、和调色板都不打架 —— 底下的按下色照旧生效，
 * 这一层只是**让这个变化看起来是"按下去"而不是"跳一下"**。
 */

#pragma once

#include <QPoint>

class QApplication;
class QColor;
class QTreeView;
class QWidget;

namespace Anim {

// —— 时长与档位：**唯一出处**（要改节奏就改这儿，别在调用点写数）——

/// 按下去那一下多快（毫秒）。
constexpr int pressInMs() { return 90; }
/// 松开之后弹回来多快。
constexpr int pressOutMs() { return 130; }
/// 换页那一下（淡入 + 上抬）。
///
/// ★ 2026-10-11：130 → **200**。原来那 130 ms 只够走 8 拍，而 `OutCubic` 又把大半的动感
///   堆在前两三拍里 —— 用户看到的是"顿一下，然后一跳到顶"（「看上去像是从下面瞬移上去的
///   没有过渡」）。200 ms 走 12~13 拍，配上 `OutSine`（每拍摊得开）才是一段**看得见**的过渡。
constexpr int appearMs() { return 200; }
/// 整块覆盖那一层（`OverlayHost`）淡进来那一下。**和换页同一个量级**（同一类转场）。
constexpr int overlayMs() { return 200; }
/// 底栏上拉面板滑上来那一下。**没动** —— 它是"这一块弹出来"，不是"一整页换过去"。
constexpr int panelMs() { return 130; }
/// 滚动条**冒出来**那一下（用户 2026-09-29：「每一次切页面的时候滚动条都是瞬间出现的」）。
/// 和换页同一个量级 —— 它得跟页面那一下一起收住，单独更快或更慢都会看成"两件事"。
constexpr int scrollBarMs() { return 200; }
/// 上拉面板的起手位比落点低多少像素。
constexpr int panelSlideDistance() { return 16; }
/// 换页时内容从下面抬多少像素。
///
/// ★ 2026-10-11：8 → 10 → **18**。前两次都在"抬"这一位上加码，可它当时根本抬不动
///   （`OutCubic` + 只有 8 拍 ⇒ 头两拍就把 10 px 走掉 5.8 px）。换了曲线、拉到 200 ms
///   之后，这一位才是这一发里**真正给眼睛看的东西** —— 18 px 摊在 12 拍上，每拍最多
///   2.3 px，是一条看得出来、又不晃的"滑上来"。
constexpr int pageRiseDistance() { return 18; }

/// 「一拍」是多少毫秒 —— **按帧走**的那几发（换页 / 覆盖层 / 滚动条）用它。
///
/// ★★ 2026-10-11：这个数是给"步进"用的 —— 为什么和怎么做整段写在 `Animations.cpp` 里
///    `runProgress()` 那一段（★★ 那几行）。一句话：那几发**不再按墙上时钟算进度**，而是
///    **每一拍推一档**。16 ms 就是这台机器上那个统一动画定时器的节奏（实测 15~16 ms 一拍）。
///
/// ★★ 同一天下午又补了一刀：**"每颗定时器最多只补发一个迟到事件"那条假设是错的**。
///    实测（`ui_shot`，真帧）主线程被占 40 ms 之后，**两拍会挤在一起**（t=46 推 1/8、
///    t=48 又推 2/8）—— 那一瞬等于把 5.8 px 和 12% 浓淡一次性推完，就是用户说的"瞬移"。
///    修法**不是**改单发链（试过：推完一档再 `start()` 下一发 ⇒ 每一拍的间隔变成
///    "16 ms + 事件循环那一趟的忙时间"，实测总时长 208 → **416 ms**，慢了一倍），
///    而是**周期 16 ms 照旧 + 离上一拍太近的那一拍原地丢掉**（判据 `stepMs()*3/4`）。
///    完整来龙去脉写在 `Animations.cpp` 的 `runProgress()` 那一段。
constexpr int stepMs() { return 16; }

/// 换页那一发起手的**不透明度**（不是 0）。
///
/// 这一位管的是**切过去之后头几十毫秒看着是什么样** —— 那一段是躲不掉的：主线程正忙着
/// 建新那一页、摆版、画第一帧，动画的**第一拍要等它忙完才来**（2026-10-11 在 `ui_shot`
/// 里量的真帧：起手帧 t=5ms `<这个值>` / +`pageRiseDistance()`，一直到 t=43ms 才动第一拍）。
/// 所以这一位是**"定住的那一帧长什么样"**和**"这一发还看得出在淡吗"**两头之间的那个点：
///
///   * 从 0 淡：定住那一帧就是垫底的窗口底色，看着是"闪一下白"。
///   * 0.5：定住的是一块半灰的，而且一站就是几十毫秒，看着是**卡住**。
///   * ★ **0.8**（2026-10-11 上午那一版）：定住那一帧确实像"一页内容刚落位"，可"淡"这
///     一半只剩 20%，整个转场就只剩一个"抬" —— 用户当天下午就报了
///     「看上去像是从下面瞬移上去的**没有过渡**」。
///   * ★ **0.65**（同一天定稿）：定住那一帧是"一页看得清、但明显还没到位"的内容，
///     剩下的 35% 浓淡摊在 `OutSine` 的十几拍上，是**看得见的一段淡**。
///
/// NOTE: 它只治"定住那一帧"和浓淡的**起点**，缓动在 `runProgress()` 里（`OutSine`），
///       映射 `pageStartOpacity() + (1 - pageStartOpacity()) * t` 写在 `pageAppear()` 里。
/// NOTE: 别的几发（整块覆盖层 `overlayAppear()`、滚动条 `scrollBarAppear()`）**照旧从 0
///       淡**：它们本来就是"从无到有"，而且没有"一大块空底"这个观感问题。
constexpr qreal pageStartOpacity() { return 0.65; }

// ★★ 2026-10-11：**换页前面那 70 ms 的"干等"整个拿掉了**（原来那一下叫 `pageDelayMs()`）。
//
//   那一段是 2026-09-29 加的（用户原话「这个框架啥的都是瞬间出现，能不能给它设定一定延迟」），
//   实现成"起手全透明 + 垫一层窗口底色，干等 70 ms 再开始淡"。它的**代价**当时没算清楚：
//   那 70 ms 里内容区**是一整块空白**（`#f0f0f0` 那种平底，`ui_shot` 当时专门拍过一帧），
//   于是每切一次选项卡都先闪一下白，再淡进来 —— 两件事，不是一个转场。
//
//   现在这一版的做法：**没有干等，直接淡**（`appearMs()` 从 160 收到 130，总时长 230 → 130）。
//   "不要瞬间铺上"这件事靠的是那一段缓动 + `pageRiseDistance()` 的上抬，不再靠等 —— 等出来的
//   "不是瞬间"，观感上就是"卡了一下"，而且中间那一段是空的，比瞬间铺上更难看。
//
//   NOTE: 垫底色那一层（`AnimEffect::setBackdrop()`）**留着**，它管的是另一件事：不垫的话
//         那些**不透明的子控件视口**（列表/树的 viewport）就成了"谁都不画"的一格，屏幕上
//         留着上一页的像素。来龙去脉见 `AnimEffect::draw()` 与 `pageStartOpacity()`。
//   NOTE: 起手那一位钉在 `pageStartOpacity()`（不是 0）—— 同一个坑的最后一格，见那里。
//
//   ★ 后续（同一天，用户接着报「动画有严重的卡顿感」）：**原来那 70 ms 干等还替另一件事打
//     了掩护** —— 等完那一段主线程已经缓过来了，动画的第一拍于是落在"不忙"的时候。干等一
//     拿掉，第一拍就落在最忙的那一下（实测晚 23~64 ms），而按墙上时钟算进度的那一发**第一
//     拍就直接跳到半路**。修法在 `stepMs()`：那几发改成**每一拍推一档**。
//     一句话记着：**这一层里任何"等一等再动"都是把问题往后挪，不是解决它。**
/// 按下时把按钮压暗**百分之几**（和悬停那一档 `Theme::rowHoverAccentPercent()` 同一个数）。
constexpr int pressDepthPercent() { return 12; }

/// 动效总开关。**默认开**；关掉之后下面这些函数全部原地返回（一个效果都不装、一个像素都不动）。
/// 三个验证工程在自己的 `main()` 头一行关掉它：那些工程要在 offscreen 下量几何和像素，
/// 半路飞进来一段动画会让"刚切过去就截图"那种判据时灵时不灵。
bool enabled();
void setEnabled(bool on);

/// 给整个应用装上"按下按钮"那个事件过滤器。**幂等**（`Theme::apply()` 会被调好几次，
/// 这里也一样可能被调好几次）。`src/main.cpp` 调它一次，验证工程不调（它们不要动效）。
bool installPressAnimation(QApplication &app);

/// 滚动条**露面**的那一瞬间：从全透明淡进来。
/// 调用方是 `installScrollBarAnimation()` 挂的那个事件过滤器（见它上面那段）；别处不用喊。
void scrollBarAppear(QWidget *bar);

/**
 * @brief 给整个应用装上"滚动条一露面就淡进来"那个事件过滤器（`QEvent::Show`）。
 *
 * 用户 2026-09-29 原话：「每一次切页面的时候滚动条都是瞬间出现的」。滚动条是**按需出现**
 * 的（内容不够长它就不在），而 Qt 出现的那一下是硬切 —— 页面在淡、它在"啪"地跳出来。
 * 这一条把它压进同一段节奏里。
 *
 * ★ 和按下那一份同一个做法（挂 `QApplication`、**从不吞事件**）：全仓每一处滚动区都不用改。
 * ★ **幂等**；`src/main.cpp` 调它一次，验证工程不调（它们不要动效）。
 */
bool installScrollBarAnimation(QApplication &app);

/**
 * @brief 换页：新那一块淡进来，**里面的内容**再从下面抬 `pageRiseDistance()`。
 * @param widget **要淡的那一块**（顶上那一档就是内容区整个 `QTabWidget`）。
 *
 * ★★ **抬的是内容，框一个像素都不动**（2026-10-11）。用户原话：「这个动画，在有框的时候
 *   框会瞬移，能不能考虑一下用其它组件之类的解决」。
 *
 *   原来这一发是**整块**（连它自己那圈外框）一起往下挪着画的。可其中有些控件是**换页前
 *   后都在的同一块** —— 内容区那张卡片和外框是 `QTabWidget` 自己画的（`ThemeBackground`
 *   在"没设图"时一个像素都不画），实例列表那棵树是自己的框 —— 于是那圈外框起手先跳下去
 *   十几像素、再滑回原处，看着就是**框在瞬移**；内容是新上来的、没有参照物，反倒像正常
 *   的滑入。修法不是"抬得少一点"，是**让框压根不参与**：抬的改成它**里面那一块**
 *   （`ui/Animations.cpp` 里的 `liftTarget()`：选项卡 ⇒ `currentWidget()`，滚动区/列表/树 ⇒ `viewport()`，
 *   剩下的 ⇒ 就是它自己），外框和四周照原位贴回去（`AnimEffect::draw()` 里那两步）。
 *
 *   于是这条函数**照样只管淡那一块**（卡片一起淡，用户 2026-09-29 要的就是这个），
 *   只是"抬"只落在内容上。
 *
 * 内层那几层换页（下载页右栏、设置页右栏…）传的就是它们**当前那一页**：那一页没有单独
 * 画的框，抬的仍然是整块。
 *
 * ★★ 淡的同时，那一块**底下先垫一层底色**（而且这一层**不跟着一起淡**）。★ 2026-10-11：
 *   原来垫它是为了填满"干等那 70 ms"（那一段整个拿掉了，见 `appearMs()` 上面那段），
 *   **现在垫它是为了整发淡的每一帧 + 内容抬起来让出来的那一条**：内容从
 *   `pageStartOpacity()` 淡到 1 的这一路上都不是全实，控件底下那些**不透明子控件**
 *   （列表/树的视口）自己又不去画 —— 不垫的话它们那一格就是"谁都不画"（屏幕上是上一帧
 *   留下的像素、`grab()` 出来是一块黑），半透明地压上去只会更花；而抬起来那一条露的
 *   就是这一层。来龙去脉写在 `AnimEffect::draw()` 里。
 *   垫哪一档颜色由调用方说（两参数那一份）：**内容抬起来那一条露的就是它**，所以垫错
 *   不报错、症状只是那一条颜色不对（比如卡片上横着一条偏灰的带子）。
 *
 * NOTE: 换页那一层是**嵌套**的（内层那几页也在 `QTabWidget` 里面）。同一时刻两层都在动
 *       只是"两件事撞在一起"，画面仍然是一层贴一张图，不会有元素跑出自己那一块。
 *
 * ★★ 这一发淡的**是一张定住的图**：起手照一次，之后每一帧都拿那一张（`AnimEffect` 里那
 *   一段）。理由：换页那一刻往往正是"内容还在往里灌"的时候 —— 典型是实例设置里「服务器
 *   列表」那一页（进页就自动测速，结果一个一个回来：行从一行字长成两行、favicon 补上、
 *   树跟着长高、滚动条冒出来）。现照现淡的话，**这一发淡的每一帧都不是同一张画面**，
 *   看着就是"动画卡卡的"（用户 2026-09-29 原话）。定住之后这一发只剩 blit，中途进来的
 *   数据照样落到控件上、只是要等它跑完才看得见（`appearMs()` 那 130 ms）。
 *
 *   NOTE: 照的时机是"第一帧真的画出来"那一刻 —— 换页那一刻先发的布局请求排在绘制请求
 *         前面（`UpdateRequest` 是低优先级），所以照到的是**已经摆好版**的那一页。
 */
void pageAppear(QWidget *widget);

/**
 * @brief 同上，只是**底下垫什么底色**由调用方指定（上面那一份垫的是顶层窗口的
 *        `QPalette::Window`）。
 * @param backdrop 起手那一帧（以及淡的过程中）这一块地方垫什么颜色。
 *
 * ★ 垫的是**这一块平时铺的底**：内层那几层（"左栏换一栏 → 右栏整块换"）那些页都活在一层
 *   滚动区里、视口铺的是 `QPalette::Base`；顶上那一档是**内容区那张卡片**，Fusion 画的
 *   就是 `QPalette::Base`（浅色下 `#fcfcfc`）。垫错不报错、也不会有东西越界 —— 症状只是
 *   这一整块偏灰（`#f0f0f0` 对 `#ffffff`）贴在页面正中，看着像"这一页闪了一下"。
 */
void pageAppear(QWidget *widget, const QColor &backdrop);

/// 整块覆盖的那一层（`OverlayHost`）淡进来。**只淡、不抬** —— 它是"整块盖住内容区"的，
/// 抬起来会在边上露出一条没盖住的缝。
void overlayAppear(QWidget *widget);

/// 展开/折叠动画。**唯一出处**：所有会展开折叠的树/表都在自己搭好之后调它一次。
/// 关掉动效时它把这一位关回去（等于回到 Qt 的出厂行为：瞬间展开）。
void animateExpansion(QTreeView *view);

/// 底栏那两块上拉面板：从落点下面 `panelSlideDistance()` 滑上来。
/// 调用方先把面板 `show()` 出来（顺序见 `BottomBarPanel::popUp()`）。
void slideUp(QWidget *window, const QPoint &target);

}  // namespace Anim
